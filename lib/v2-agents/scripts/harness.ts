/**
 * pnpm --filter @workspace/v2-agents harness -- [options]
 *
 *   --rule family/tieBreaker   a player with that rule (repeat for several players on shared lines)
 *   --agent example|simple|thorough|bold   the shipped agent each player runs (default example)
 *   --source file.py|file.ts   run this program instead (every player)
 *   --language typescript|python   (default typescript)
 *   --budget 500  --lines 8  --seed s1  --variant line-z (or grid-4-d10: the grid; "lines" are then boards)
 *   --pool [file.md]           every family and tie-breaker, solo, with each shipped agent, and some three-player
 *                              tables; prints Markdown (or writes it to the file)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { parseArgs } from "node:util";
import type { ObjectType } from "@workspace/v2-core";
import { gridType } from "@workspace/v2-grid";
import { lineType } from "@workspace/v2-linear";
import type { Language } from "@workspace/v2-sandbox";
import { exampleFor, hasStarters, sandboxes, startersFor, type AgentKind, type ShippedLanguage } from "../src/index.ts";
import { byView, formatReport, runHarness, utilityCell, type HarnessPlayer } from "../src/harness.ts";

const { values } = parseArgs({
  options: {
    rule: { type: "string", multiple: true }, agent: { type: "string", default: "example" }, source: { type: "string" },
    language: { type: "string", default: "typescript" }, budget: { type: "string", default: "500" }, lines: { type: "string", default: "8" },
    seed: { type: "string", default: "s1" }, variant: { type: "string", default: "line-z" }, pool: { type: "string" },
  },
  allowPositionals: true,
});
// The object type whose variant was asked for (line-z, line-q, grid-4-d10, ...).
const type = ([lineType, gridType] as ObjectType<any>[]).find(t => t.variants.some(v => v.id === values.variant));
if (!type) throw new Error(`no object type has the variant ${values.variant}`);
const variant = type.variants.find(v => v.id === values.variant)!;
const language = values.language as ShippedLanguage;
const budget = Number(values.budget), lines = Number(values.lines);
const boxes = sandboxes();

function player(spec: string, kind: AgentKind, name = spec): HarnessPlayer {
  const [family, tieBreaker] = spec.split("/") as [string, string | undefined];
  const f = type.families.find(x => x.id === family);
  if (!f) throw new Error(`no family ${family}`);
  const tb = tieBreaker ?? f.tieBreakers[0]!.id;
  const params = f.dealable(variant)[0] as Record<string, unknown>;
  let program;
  if (values.source) {
    program = { language: (values.source.endsWith(".py") ? "python" : "typescript") as Language, source: readFileSync(values.source, "utf8") };
  } else {
    const a = kind === "example" ? exampleFor(family, tb, language) : startersFor(family, language, tb).find(x => x.kind === kind);
    if (!a) throw new Error(`no ${kind} agent for ${spec}`);
    program = { language: a.language, source: a.source };
  }
  return { name, rule: { family, params, tieBreaker: tb }, program };
}

const f1 = (x: number) => (Math.round(x * 10) / 10).toFixed(1);

async function pool(): Promise<string> {
  const out = [
    "# Agent harness: the rule families compared",
    "",
    `Generated by \`pnpm --filter @workspace/v2-agents harness -- --pool\` on ${variant.id}: ${lines} shared newborn lines (seed ${values.seed}), ` +
    `${budget} energy per player (or 400 acts), the players taking turns, no accrual, the rule's first dealable numbers. Utilities (a distance negated) and bits are means over the lines; ` +
    "bits are looked up in the rule's committed value function (lib/v2-valuation values), its top is the best knot's bits, and lines past the best knot are extrapolated.",
    "",
    "## Solo: one player, each shipped agent",
    "",
    "| Rule | Agent | Acts made / skipped | energy spent | Main part (utility, start → end) | Tie-breaker | Bits a line (start → end / top) | Lines past the top knot | Bits gained | Bits per 100 energy | energy on reads | energy on changes |",
    "|---|---|---|--:|---|---|---|---|--:|--:|---|---|",
  ];
  for (const f of type.families.filter(x => hasStarters(x.id))) for (const tb of f.tieBreakers) for (const kind of ["example", "simple", "thorough", "bold"] as const) {
    const spec = `${f.id}/${tb.id}`;
    if (!exampleFor(f.id, tb.id, "typescript")) continue;   // no agents written for this tie-breaker yet (starters.ts undescribed())
    const r = await runHarness(boxes, { type, variant, players: [player(spec, kind)], budget, lines, seed: values.seed! });
    const x = r.rules[0]!, s = r.spend[0]!;
    const status = x.bits ? "" : " (no value function)";
    out.push(`| ${spec}${status} | ${kind} | ${s.acts.committed} / ${s.acts.skipped} | ${f1(s.spent)} | ${utilityCell(x, 0)} | ${utilityCell(x, 1)} | ` +
      `${x.bits ? `${f1(x.bits.start)} → ${f1(x.bits.end)} / ${f1(x.bits.top)}` : "–"} | ${x.bits ? `${x.bits.beyond.start} → ${x.bits.beyond.end}` : "–"} | ` +
      `${x.bitsGained === null ? "–" : f1(x.bitsGained)} | ${x.bitsGained === null || s.spent === 0 ? "–" : f1(100 * x.bitsGained / s.spent)} | ` +
      `${byView(s.reads)} | ${byView(s.changes)} |`);
  }
  if (type.id === "grid") {
    // Points: three players on shared boards, every player on the same kind of agent in each table, so the
    // points-aware starters can be compared with Naive and the examples.
    const tables = [
      ["mirrormancer/middle", "magic-eighteen/first-column", "opposite-nines/top-half"],
      ["two-pair/corners", "strangers/primes", "leapfrog/zeros"],
      ["spread-of-three/corners", "crosswise-threes/fold-line", "magic-eighteen/odd"],
    ];
    for (const t of tables) for (const s of t) if (!exampleFor(s.split("/")[0]!, s.split("/")[1]!, "typescript")) throw new Error(`the grid tables name ${s}, which has no shipped agents`);
    out.push("", "## Three players on shared boards, by agent", "",
      "Each table is three players with different rules acting on the same boards, every player running the same kind of",
      "shipped agent; every rule is measured on every board, and points are π_i = n_i · Σ_{j≠i} n_j per board, summed.", "");
    for (const specs of tables) for (const kind of ["example", "simple", "thorough", "bold", "naive"] as const) {
      const r = await runHarness(boxes, { type, variant, players: specs.map((s, i) => player(s, kind, `P${i + 1}`)), budget, lines, seed: values.seed! });
      out.push(`### ${kind}: ${specs.join(" · ")}`, "", formatReport(r), "");
    }
    return out.join("\n");
  }
  out.push("", "## Three players on shared lines (examples)", "",
    "Each table is three players with different rules acting on the same lines; every rule is measured on every line, so a",
    "rule's bits can fall when another player's agent pulls the lines elsewhere.", "");
  const tables = [
    ["m-meets-c/size", "prime-gradient/prime", "triangle-area/legs"],
    ["whole-intercept/spf", "m-meets-c/meetPrime", "treasure/prime-terms"],
    ["square-area/omega", "triangle-area/even", "crossing-check/whole"],
  ];
  for (const specs of tables) {
    const r = await runHarness(boxes, { type, variant, players: specs.map((s, i) => player(s, "example", `P${i + 1}`)), budget, lines, seed: values.seed! });
    out.push(`### ${specs.join(" · ")}`, "", formatReport(r), "");
  }
  return out.join("\n");
}

try {
  if (values.pool !== undefined) {
    const text = await pool();
    if (values.pool) writeFileSync(values.pool, text); else process.stdout.write(text);
  } else {
    if (!values.rule?.length) throw new Error("give --rule family/tieBreaker (repeat for several players) or --pool");
    const players = values.rule.map((s, i) => player(s, values.agent as AgentKind, values.rule!.length > 1 ? `P${i + 1}` : s));
    const r = await runHarness(boxes, { type, variant, players, budget, lines, seed: values.seed! });
    console.log(formatReport(r));
  }
} finally {
  await boxes.close();
}
