#!/usr/bin/env node
/**
 * Bundles worker.mjs (the engines, no npm dependencies: the TypeScript compiler and QuickJS are loaded
 * from paths the host resolves) into generated/worker-source.mjs, a module exporting the worker's code
 * as one string. index.mjs starts workers from that string (`eval: true`), so worker_threads work even
 * where this package is bundled into someone else's code (a Convex Node action).
 *
 *   node scripts/build-worker.mjs          # rewrite generated/worker-source.mjs
 *   node scripts/build-worker.mjs --check  # exit 1 if it is stale (the tests run this)
 */
import { build } from "esbuild";
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";

const PACKAGE = fileURLToPath(new URL("..", import.meta.url));
const OUT = `${PACKAGE}generated/worker-source.mjs`;

export async function workerModule() {
  const result = await build({
    entryPoints: [`${PACKAGE}worker.mjs`], bundle: true, write: false, platform: "node", format: "cjs",
    target: "node22", legalComments: "none", logLevel: "silent",
  });
  const code = result.outputFiles[0].text;
  return "// Generated by scripts/build-worker.mjs from worker.mjs and engine/*. Do not edit.\n"
    + `export default ${JSON.stringify(code)};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = await workerModule();
  if (process.argv.includes("--check")) {
    if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== text) {
      console.error("generated/worker-source.mjs is stale: run node scripts/build-worker.mjs");
      process.exit(1);
    }
  } else {
    mkdirSync(`${PACKAGE}generated`, { recursive: true });
    writeFileSync(OUT, text);
    console.log(`Wrote ${OUT} (${text.length} bytes)`);
  }
}
