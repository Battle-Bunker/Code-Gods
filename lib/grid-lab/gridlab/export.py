"""Export Grid Lab results for the game server: calibration tables, dealable draws and parity fixtures.

    cd lib/grid-lab && python3 -m gridlab.export [--types 5,base10,rgby 3,base10,rgb ...] [--processes 4]

Writes, for each GridType (default: the four shipped ones),

  lib/game-utilities/src/grid/data/<size>_<symbols>_<colours>.ts   (shipped; read by the server)
  lib/game-utilities/test/fixtures/grid/<size>-<symbols>-<colours>.json   (parity fixtures; tests only)

and lib/game-utilities/src/grid/data/index.ts listing them. Each data module exports one JSON string
(parsed lazily), so the multi-megabyte tables cost the TypeScript checker nothing and bundle as-is. Everything is deterministic: params are
enumerated with fixed seeds, tables are seeded by `calibrate.seed_key`, fixtures use fixed seeds.

Data file (FORMAT below, versioned by DATA_VERSION):
  gridType  {size, symbols, colours, key}
  families  [{id, name, emoji, theme, camp, layers, requires, defence}]   one per dealable family
  draws     [{family, params, table, penaltyTable, summary, card, penalty}]   the dealable draws:
            `params` are Grid Lab params (tuples as lists); `table` / `penaltyTable` key `tables`;
            `card` is the kid-readable Python utility function (gridlab/rules/cards.py) and
            `summary` its plain-language incentive. `penalty` (defence goals only) is
            {family, name, summary, comparative}.
  tables    {key: {family, params, tuple, levels, bits, slope, exact, priorMean, hbar}}
            Survival tables (calibrate.Survival): `levels` are strictly increasing ordinals (ints, or
            int lists for tuple ordinals, compared lexicographically) and `bits` the surprisal at
            each level. Lookups between, below and above levels follow Survival._bits exactly
            (see lib/game-utilities grid scoring). `hbar` = E_μ[hinge(surprisal)] for penalty
            tables, used by net bits (gridlab/defence.py). Draws in one symmetry orbit
            (family.canonical) share a key, so one table covers every param draw in the orbit.

Fixture file: a pool of grids (canonical ASCII) and, per table, Grid Lab's ordinal and surprisal for
a list of pool indices, so TypeScript ports can be checked value for value.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import math
import time
from pathlib import Path

import numpy as np

from . import calibrate as cal
from .core import COLOUR_LETTERS as _CORE_LETTERS, Grid, GridType, spawn_batch
from .defence import hinge
from .family import Draw
from .rules import DEFENCE_FAMILIES, shortlist
from .rules.cards import CARDS

DATA_VERSION = 1
FORMAT = "code-gods-grid-data"
ROOT = Path(__file__).resolve().parents[3]
DATA_DIR = ROOT / "lib" / "game-utilities" / "src" / "grid" / "data"
FIXTURE_DIR = ROOT / "lib" / "game-utilities" / "test" / "fixtures" / "grid"
DEFAULT_TYPES = ("5,base10,rgby", "3,base10,rgb", "4,base12,rgb", "6,cards,rainbow6")
SAMPLES = 4000          # param draws sampled per family when enumerating its draws
MAX_DRAWS = 48          # cap on dealable draws per family and GridType (deterministic subset)
FIX_RANDOM = 40         # random grids in the fixture pool
FIX_PER_TABLE = 24      # fixture grids checked per table

SYMBOL_CODES = {
    "cards": [r + s for s in "SHDC" for r in "A23456789TJQK"],
}
COLOUR_LETTERS = {k: "".join(v) for k, v in _CORE_LETTERS.items()}


def slug(gt: GridType) -> str:
    return f"{gt.size}_{gt.symbols}_{gt.colours}"


HEADER = "// Generated by lib/grid-lab/gridlab/export.py (python3 -m gridlab.export). Do not edit.\n"


def write_module(path: Path, payload: dict) -> None:
    """A TypeScript module whose default export is the payload as a JSON string."""
    text = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    path.write_text(HEADER + "export default " + json.dumps(text, ensure_ascii=False) + ";\n")


def codes(gt: GridType) -> list[str]:
    return SYMBOL_CODES.get(gt.symbols) or list("0123456789ABCDEF"[:gt.S])


def encode(g: Grid, gt: GridType) -> str:
    """Canonical ASCII wire format (architecture §6; lib/game-core/src/grid.ts)."""
    sc, cl = codes(gt), COLOUR_LETTERS[gt.colours]
    s, c = g.sym.tolist(), g.col.tolist()
    return "/".join(",".join(sc[s[r][k]] + cl[c[r][k]] for k in range(gt.N)) for r in range(gt.N))


def jsonable(o):
    if isinstance(o, dict):
        return {str(k): jsonable(v) for k, v in sorted(o.items())}
    if isinstance(o, (list, tuple)):
        return [jsonable(x) for x in o]
    if isinstance(o, (np.integer,)):
        return int(o)
    if isinstance(o, (np.floating, float)):
        return float(o)
    if isinstance(o, np.ndarray):
        return jsonable(o.tolist())
    return o


def ordinal_json(o):
    return [int(x) for x in o] if isinstance(o, tuple) else int(o)


def table_key(draw: Draw, gt: GridType) -> str:
    return draw.family.id + ":" + hashlib.sha256(cal.seed_key(draw, gt).encode()).hexdigest()[:12]


def emoji_of(card: str) -> str:
    first = card.splitlines()[0]
    return first[2:].split(" ", 1)[0] if first.startswith("# ") else ""


def dealable_families(gt: GridType):
    """The 31 shortlisted families (all have kid cards) plus the defence variants built on them."""
    short = shortlist()
    ids = {f.id for f in short}
    out = [f for f in short if f.available(gt)]
    out += [f for f in DEFENCE_FAMILIES if f.base is not None and f.base.id in ids and f.available(gt)]
    return out


def enumerate_draws(f, gt: GridType) -> list[dict]:
    rng = np.random.default_rng(int(hashlib.sha256(f"{f.id}|{gt.key}".encode()).hexdigest()[:8], 16))
    seen: dict[str, dict] = {}
    for _ in range(SAMPLES):
        p = f.sample(rng, gt)
        seen.setdefault(cal.canonical_json(p), p)
    keys = sorted(seen)
    if len(keys) > MAX_DRAWS:
        pick = np.random.default_rng(len(keys)).choice(len(keys), MAX_DRAWS, replace=False)
        keys = [keys[i] for i in sorted(pick)]
    return [seen[k] for k in keys]


def card_for(f, p, gt: GridType) -> str:
    base = f.base or f
    q = {k: v for k, v in p.items() if k != "defence"} if f.base is not None else p
    return CARDS[base.id](q, gt)


def export_table(t: cal.Survival, draw: Draw, gt: GridType, penalty: bool) -> dict:
    levels = list(t._lv) + [x for x in t.extra_levels.tolist()]
    from .family import key_to_ordinal
    ords = sorted({key_to_ordinal(x) for x in levels})
    bits = [float(t.surprisal(o)) for o in ords]
    for a, b in zip(bits, bits[1:]):
        assert b > a, f"{draw.family.id}: surprisal not strictly increasing at exported levels"
    out = {"family": draw.family.id, "params": jsonable(cal.canonical_params(draw, gt)),
           "tuple": isinstance(ords[0], tuple), "levels": [ordinal_json(o) for o in ords],
           "bits": [round(b, 9) for b in bits], "slope": float(t.slope), "exact": t.exact is not None,
           "priorMean": round(t.prior_mean_bits(), 9)}
    if penalty:
        out["hbar"] = round(t.prior_mean_bits(f=hinge), 9)
    return out


def fixture_pool(gt: GridType, families) -> tuple[list[Grid], dict[str, list[int]]]:
    """Random grids shared by every table, plus each family's exemplar and perturbations of it."""
    rng = np.random.default_rng(7)
    S, C = spawn_batch(gt, rng, FIX_RANDOM)
    pool = [Grid(a, b) for a, b in zip(S, C)]
    N = gt.N
    for k in range(min(gt.C, 3)):   # low-entropy grids make ties and rare events common
        pool.append(Grid(np.full((N, N), k % gt.S, np.uint8), np.full((N, N), k, np.uint8)))
        cs = rng.choice(gt.C, 2, replace=False)
        ss = rng.choice(gt.S, 2, replace=False)
        pool.append(Grid(rng.choice(ss, (N, N)).astype(np.uint8), rng.choice(cs, (N, N)).astype(np.uint8)))
    extra: dict[str, list[int]] = {}
    return pool, extra


def main(argv=None):
    ap = argparse.ArgumentParser(prog="gridlab.export")
    ap.add_argument("--types", nargs="*", default=list(DEFAULT_TYPES))
    ap.add_argument("--processes", type=int, default=4)
    a = ap.parse_args(argv)
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    FIXTURE_DIR.mkdir(parents=True, exist_ok=True)
    index = []
    for spec in a.types:
        n, s, c = spec.split(",")
        gt = GridType(int(n), s, c)
        t0 = time.time()
        fams = dealable_families(gt)
        draws = [(f, p) for f in fams for p in enumerate_draws(f, gt)]
        stats = cal.precompute([Draw(f, p) for f, p in draws], gt, processes=a.processes)
        tables: dict[str, dict] = {}
        originals: dict[str, Draw] = {}   # table key -> a draw with Grid Lab's own params objects
        draw_rows, fam_rows = [], []
        for f in fams:
            card = card_for(f, f.sample(np.random.default_rng(0), gt), gt)
            fam_rows.append({"id": f.id, "name": f.name, "emoji": emoji_of(card), "theme": f.theme,
                             "camp": f.camp, "layers": sorted(f.layers), "requires": f.requires.describe(),
                             "defence": f.penalty is not None})
        for f, p in draws:
            d = Draw(f, p)
            rd, pd = d.reward_draw(), d.penalty_draw()
            rk = table_key(rd, gt)
            if rk not in tables:
                tables[rk] = export_table(cal.survival(rd, gt), rd, gt, penalty=False)
                originals[rk] = rd
            pk = None
            pen = None
            if pd is not None:
                pk = table_key(pd, gt)
                if pk not in tables:
                    tables[pk] = export_table(cal.survival(pd, gt), pd, gt, penalty=True)
                    originals[pk] = pd
                from .rules.defence import comparative
                pen = {"family": pd.family.id, "name": pd.family.name, "summary": pd.summary(gt),
                       "comparative": comparative(pd, gt)}
            card = card_for(f, p, gt)
            draw_rows.append({"family": f.id, "params": jsonable(p), "table": rk, "penaltyTable": pk,
                              "summary": d.summary(gt), "card": card, "penalty": pen})
        data = {"format": FORMAT, "version": DATA_VERSION, "estimator": cal.ESTIMATOR_VERSION,
                "gridType": {"size": gt.size, "symbols": gt.symbols, "colours": gt.colours, "key": gt.key},
                "families": fam_rows, "draws": draw_rows, "tables": tables}
        write_module(DATA_DIR / f"{slug(gt)}.ts", data)

        # parity fixtures: one representative draw per table
        pool, _ = fixture_pool(gt, fams)
        rng = np.random.default_rng(11)
        cases = []
        for key, tab in tables.items():
            f, p = originals[key].family, originals[key].params
            idx = sorted(rng.choice(len(pool), min(FIX_PER_TABLE, len(pool)), replace=False).tolist())
            if f.exemplar is not None:
                e = f.exemplar(p, gt)
                pool.append(e)
                idx.append(len(pool) - 1)
                for _ in range(3):
                    s_, c_ = e.sym.copy(), e.col.copy()
                    r_, k_ = rng.integers(gt.N, size=2)
                    s_[r_, k_] = rng.integers(gt.S)
                    pool.append(Grid(s_, c_))
                    idx.append(len(pool) - 1)
            survival = cal.survival(Draw(f, p), gt)
            ords = [f.ordinal(pool[i], p, gt) for i in idx]
            bits = [float(survival.surprisal(o)) for o in ords]
            cases.append({"table": key, "family": f.id, "params": jsonable(p), "grids": idx,
                          "ordinals": [ordinal_json(o) for o in ords],
                          "bits": [round(b, 9) for b in bits]})
        fixture = {"format": FORMAT + "-fixture", "version": DATA_VERSION, "gridType": data["gridType"],
                   "pool": [encode(g, gt) for g in pool], "cases": cases}
        (FIXTURE_DIR / f"{slug(gt)}.json").write_text(json.dumps(fixture, separators=(",", ":")) + "\n")
        index.append({"key": gt.key, "module": slug(gt), "size": gt.size, "symbols": gt.symbols,
                      "colours": gt.colours, "families": len(fam_rows), "draws": len(draw_rows),
                      "tables": len(tables)})
        print(f"{gt.key}: {len(fam_rows)} families, {len(draw_rows)} draws, {len(tables)} tables "
              f"({stats['built']} built) in {time.time() - t0:.0f}s", flush=True)
    write_index(index)


def write_index(index: list[dict]) -> None:
    """index.ts: the shipped GridTypes and a lazy loader per data module (merged with existing entries)."""
    path = DATA_DIR / "index.ts"
    old = {}
    if path.exists():
        start = path.read_text().index("export const GRID_DATA_INDEX = ") + len("export const GRID_DATA_INDEX = ")
        old = {e["key"]: e for e in json.loads(path.read_text()[start:].split(";\n", 1)[0])["gridTypes"]}
    old.update({e["key"]: e for e in index})
    entries = sorted(old.values(), key=lambda e: (e["size"], e["symbols"], e["colours"]))
    meta = {"format": FORMAT + "-index", "version": DATA_VERSION, "estimator": cal.ESTIMATOR_VERSION,
            "gridTypes": entries}
    lines = [HEADER]
    lines += [f'import m{i} from "./{e["module"]}.ts";\n' for i, e in enumerate(entries)]
    lines += [f"export const GRID_DATA_INDEX = {json.dumps(meta)};\n",
              "/** Raw JSON text of each GridType's data module, keyed by GridType key. Parse lazily. */\n",
              "export const GRID_DATA_TEXT: Record<string, string> = {\n"]
    lines += [f'  "{e["key"]}": m{i},\n' for i, e in enumerate(entries)]
    lines.append("};\n")
    path.write_text("".join(lines))


if __name__ == "__main__":
    main()
