// Regenerates docs/catalog.md: every family, an example draw, its source, and how it
// scores against the engine's spawn distribution (uniform over the domain).
// Usage: pnpm --filter @workspace/game-utilities calibrate > lib/game-utilities/docs/catalog.md
import { FAMILIES, card, utility } from "../src/index.ts";
import { spawnSample, DEFAULT_DOMAINS, seeded } from "../test/support.ts";

const SAMPLES = 20000;
const rng = seeded(20261020);
const rows: string[] = [];
const sections: string[] = [];
for (const f of FAMILIES) {
  const domain = DEFAULT_DOMAINS[f.objectType];
  let total = 0, over10 = 0, over50 = 0, max = 0;
  for (let i = 0; i < SAMPLES; i++) {
    const u = utility({ familyId: f.id, params: f.sample(rng) }, spawnSample(domain, rng));
    total += u; max = Math.max(max, u);
    if (u > 0.1) over10++;
    if (u > 0.5) over50++;
  }
  rows.push(`| ${f.objectType} | [${f.name}](#${f.id}) | ${(total / SAMPLES).toFixed(4)} | ${(100 * over10 / SAMPLES).toFixed(2)}% | ${(100 * over50 / SAMPLES).toFixed(3)}% | ${max.toFixed(3)} |`);
  const example = card({ familyId: f.id, params: f.sample(rng) });
  sections.push(`### ${f.name}\n<a id="${f.id}"></a>\n\n*${f.objectType} · ${f.theme}*\n\nExample draw: ${example.summary}\n\n\`\`\`python\n${example.source.python}\`\`\``);
}
console.log(`# Utility function catalog

Generated by \`scripts/calibrate.ts\`; do not edit by hand.

## Calibration against random spawns

${SAMPLES} spawned objects per family, each scored by a freshly drawn utility function of that
family. Spawns are uniform: signed 32-bit integers, or ASCII strings uniform by rank (so almost
always 128 characters of noise).

| Type | Family | Mean utility | P(u > 0.1) | P(u > 0.5) | Max seen |
|---|---|---|---|---|---|
${rows.join("\n")}

## Families

${sections.join("\n\n")}`);
