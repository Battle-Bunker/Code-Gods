#!/usr/bin/env node
/**
 * Embeds the trusted guest sources (guest/*.js, guest/*.py, python/guest.py) as src/guest.gen.ts, so a bundler (the
 * engine's Convex Node actions) carries them: nothing in the sandbox reads its own files at run time.
 *   node scripts/gen-guest.mjs [--check]
 */
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(root, "src", "guest.gen.ts");
export function generate() {
  const files = {};
  for (const f of readdirSync(join(root, "guest")).sort()) files[`guest/${f}`] = readFileSync(join(root, "guest", f), "utf8");
  files["python/guest.py"] = readFileSync(join(root, "python", "guest.py"), "utf8");
  return `/** Generated by scripts/gen-guest.mjs from guest/ and python/guest.py: do not edit. */\nexport const GUEST_FILES: Readonly<Record<string, string>> = ${JSON.stringify(files, null, 1)};\n`;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = generate();
  if (process.argv.includes("--check")) {
    if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== text) { console.error("src/guest.gen.ts is stale: run node scripts/gen-guest.mjs"); process.exit(1); }
  } else writeFileSync(OUT, text);
}
