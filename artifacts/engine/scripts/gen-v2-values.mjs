#!/usr/bin/env node
/**
 * Bundles the committed value functions (lib/v2-valuation/values/<variant>/<family>/*.json, spec §7.0, owner decision 23)
 * into convex/v2/valuesIndex.gen.ts and valuesCurves.gen.ts: what the server needs to look up a state's bits at its actual score (the knots and the
 * tail rule; `valueLookup` from @workspace/v2-valuation), without the diagnostics, and the uniqueness tables
 * (lib/v2-valuation/uniqueness, owner decision 24). Each rule's curve is a JSON string, parsed on its first lookup
 * (values.ts): nearly every server module loads this file, and parsing all the curves as object literals took about
 * 260 ms per cold load, near the 1 s limit under load (playtest round 24); the strings load in a fifth of that.
 *
 *   node scripts/gen-v2-values.mjs           write the file
 *   node scripts/gen-v2-values.mjs --check   exit 1 if it is stale
 */
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(root, "..", "..", "lib", "v2-valuation", "values");
/** The index (each rule's head, the uniqueness tables): small, read by every module that names a rule. */
const OUT_INDEX = join(root, "convex", "v2", "valuesIndex.gen.ts");
/** The curves: one string, parsed on first use, so a module that loads them pays a string, not a 9 MB object literal. */
const OUT_CURVES = join(root, "convex", "v2", "valuesCurves.gen.ts");
const UNIQ = join(root, "..", "..", "lib", "v2-valuation", "uniqueness");

export function generate() {
  const rows = [], curves = {};
  for (const variant of readdirSync(SRC).sort())
    for (const family of readdirSync(join(SRC, variant)).sort())
      for (const file of readdirSync(join(SRC, variant, family)).filter(f => f.endsWith(".json")).sort()) {
        const v = JSON.parse(readFileSync(join(SRC, variant, family, file), "utf8"));
        rows.push({ ruleKey: v.ruleKey, variant: v.variant, family: v.family, params: v.params, tieBreaker: v.tieBreaker, contentHash: v.contentHash, measuredTo: v.knots.reduce((m, k) => Math.max(m, k.bits), 0) });
        curves[v.ruleKey] = JSON.stringify(v.tree ? { knots: v.knots, tail: v.tail, tree: v.tree } : { knots: v.knots, tail: v.tail });
      }
  const uniqueness = existsSync(UNIQ) ? readdirSync(UNIQ).filter(f => f.endsWith(".json")).sort().map(f => {
    const t = JSON.parse(readFileSync(join(UNIQ, f), "utf8"));
    return { variant: t.variant, ns: t.ns, heldMass: t.heldMass };
  }) : [];
  // All curves in one string, each rule's JSON at [start, end) recorded in its index row: a lookup parses its slice only.
  let all = "";
  for (const row of rows) { const c = curves[row.ruleKey]; row.curve = [all.length, all.length + c.length]; all += c; }
  const index = `/** Generated by scripts/gen-v2-values.mjs from lib/v2-valuation/values: do not edit. */
import type { ValueFunction } from "@workspace/v2-valuation";

export type ValueRecord = Pick<ValueFunction, "ruleKey" | "variant" | "family" | "params" | "tieBreaker" | "knots" | "tail" | "tree" | "contentHash">;

/** Every rule with a value function, without its curve (values.ts \`valueRecord\` adds it from valuesCurves.gen.ts), with the bits at its furthest measured knot and where its curve is in CURVES. */
export const VALUE_INDEX: readonly (Omit<ValueRecord, "knots" | "tail" | "tree"> & { measuredTo: number; curve: readonly [number, number] })[] = ${JSON.stringify(rows)};

/** The uniqueness correction per variant (spec §2.6): apply with withUniqueness(lookup, table, objects in the game). */
export const UNIQUENESS: readonly { variant: string; ns: readonly number[]; heldMass: readonly number[] }[] = ${JSON.stringify(uniqueness)};
`;
  // One string literal, not an object literal: evaluating 511 keys took ~0.4 s per cold isolate (test/unit/v2-values-load).
  const curvesText = `/** Generated by scripts/gen-v2-values.mjs from lib/v2-valuation/values: do not edit. Each rule's curve (\`{ knots, tail }\`, and \`tree\` for a tree-valued rule) as JSON, by ruleKey, concatenated in one string at the offsets in valuesIndex.gen.ts: values.ts parses a rule's slice on its first lookup. */
export const CURVES: string = ${JSON.stringify(all)};
`;
  return { index, curves: curvesText };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = generate(), files = [[OUT_INDEX, out.index], [OUT_CURVES, out.curves]];
  if (process.argv.includes("--check")) {
    for (const [file, text] of files) if (!existsSync(file) || readFileSync(file, "utf8") !== text) { console.error(`${file} is stale: run node scripts/gen-v2-values.mjs`); process.exit(1); }
  } else for (const [file, text] of files) writeFileSync(file, text);
}
