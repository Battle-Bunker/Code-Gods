"""Export the mutator catalogue and cost tables for the game server, plus TypeScript parity fixtures.

    cd lib/grid-lab && python3 -m gridlab.export_mutators [--types 5,base10,rgby ...]

Writes, for each GridType (default: the four shipped ones, the same list as gridlab/export.py),

  lib/game-utilities/src/grid/data/mutators_<size>_<symbols>_<colours>.ts   (shipped; read by the server)
  lib/game-utilities/test/fixtures/grid/mutators_<size>_<symbols>_<colours>.json   (parity fixtures)

and lib/game-utilities/src/grid/data/mutators_index.ts listing them. Each data module exports one JSON
string (parsed lazily by src/grid/mutators.ts), like the calibration modules written by export.py.

Data file (FORMAT, versioned by DATA_VERSION):
  gridType   {size, symbols, colours, key}
  knobs      COST_KNOBS (for the record; the costs below already include them)
  available  number of mutators available in this GridType (the log2 tool base)
  mutators   [{id, name, summary, layer, bijective, scopes, fields, count}] in MUTATORS order;
             `fields` are the parameter field names in prefix-code order
  costPool   [[decisionBits, physicalBits], ...]  distinct cost pairs, rounded to 1e-6
  costs      {<id>: {rows, cost}}: `rows` are every parameter setting in `Mutator.space` order, one
             array per setting holding the value of each field in `fields` order (null = the field
             is absent for that setting; tuples as arrays), and `cost[i]` indexes `costPool`.
             The params object of row i is {fields[j]: rows[i][j] for non-null j}; its canonical JSON
             (sorted keys, no spaces) is the lookup key. Anything not in a table is an invalid call.
  decision = mult × (base + describe + measure), physical = mult × (erase + move)  (Mutator.terms)

Fixture file: a pool of grids (canonical ASCII), per mutator `apply` cases [grid index, params,
expected ASCII or null for a no-op], `describe` cases [params, text, Mutator.cost], `spaceCounts`
(|Mutator.space| counted independently of the data file), and a few call sequences
(Program-style: no-op steps skipped, null when the final grid equals the start).
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

import numpy as np

from . import mutators as M
from .core import Grid, GridType
from .export import DATA_DIR, DEFAULT_TYPES, FIXTURE_DIR, encode, fixture_pool, slug

DATA_VERSION = 1
FORMAT = "code-gods-grid-mutators"
HEADER = "// Generated by lib/grid-lab/gridlab/export_mutators.py (python3 -m gridlab.export_mutators). Do not edit.\n"
APPLY_CASES = 60
DESCRIBE_CASES = 10
SEQUENCES = 24


def jsonable(o):
    if isinstance(o, dict):
        return {str(k): jsonable(v) for k, v in sorted(o.items())}
    if isinstance(o, (list, tuple)):
        return [jsonable(x) for x in o]
    if isinstance(o, np.integer):
        return int(o)
    if isinstance(o, bool) or o is None:
        raise TypeError(f"unexpected param value {o!r}")
    return o


def canonical(p: dict) -> str:
    return json.dumps(jsonable(p), sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def write_module(path: Path, payload: dict) -> None:
    text = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    path.write_text(HEADER + "export default " + json.dumps(text, ensure_ascii=False) + ";\n")


def split_cost(m: M.Mutator, p: dict, gt: GridType) -> tuple[float, float]:
    t = m.terms(p, gt)
    d = t["mult"] * (t["base"] + t["describe"] + t["measure"])
    ph = t["mult"] * (t["erase"] + t["move"])
    d, ph = round(float(d), 6), round(float(ph), 6)
    assert abs(d + ph - m.cost(p, gt)) <= 1e-5, (m.id, p)
    assert d > 0 and ph >= 0, (m.id, p, d, ph)
    return d, ph


def build_data(gt: GridType) -> dict:
    avail = M.available(gt)
    pool: dict[tuple[float, float], int] = {}
    pool_list: list[list[float]] = []
    costs, infos = {}, []
    for m in avail:
        names = [f.name for f in m.fields]
        rows, idx, seen = [], [], set()
        for p in m.space(gt):
            key = canonical(p)
            assert key not in seen, (m.id, key)
            seen.add(key)
            q = jsonable(p)
            rows.append([q.get(n) for n in names])
            pair = split_cost(m, p, gt)
            if pair not in pool:
                pool[pair] = len(pool_list)
                pool_list.append(list(pair))
            idx.append(pool[pair])
        costs[m.id] = {"rows": rows, "cost": idx}
        infos.append({"id": m.id, "name": m.name, "summary": m.summary, "layer": m.layer,
                      "bijective": m.bijective, "scopes": list(m.scopes), "fields": names, "count": len(rows)})
    return {"format": FORMAT, "version": DATA_VERSION,
            "gridType": {"size": gt.size, "symbols": gt.symbols, "colours": gt.colours, "key": gt.key},
            "knobs": jsonable(M.COST_KNOBS), "available": len(avail), "mutators": infos,
            "costPool": pool_list, "costs": costs}


def structured_grids(gt: GridType, rng: np.random.Generator) -> list[Grid]:
    """Low-entropy grids beyond export.fixture_pool's: stripes, checkers, near-constant, ramps."""
    N, S, C = gt.N, gt.S, gt.C
    r, c = np.indices((N, N))
    out = [
        Grid((r * N + c) % S, r % C),                                   # counting run, colour stripes
        Grid(np.zeros((N, N)), (r + c) % 2),                            # chessboard, constant symbol
        Grid(rng.choice(rng.choice(S, 2, replace=False), (N, N)), np.where(c == 2 % N, 1, 0)),
        Grid((r + c) % S, (r + c) % C),                                 # diagonal rainbow
    ]
    g = rng.integers(0, S, (N, N)); k = rng.integers(0, C, (N, N))
    k[:] = 0; k[N // 2, N // 2] = C - 1                               # one odd cell
    out.append(Grid(g, k))
    # blend fodder: two parent colours in random patches (if Mixable), else two colours
    rec = M._recipes(gt)
    a, b = (rec[0][0], rec[0][1]) if rec else (0, 1)
    out.append(Grid(rng.integers(0, S, (N, N)), rng.choice([a, b, (b + 1) % C], (N, N))))
    out.append(Grid(rng.integers(0, S, (N, N)), rng.choice([a, b], (N, N))))
    return out


def build_fixture(gt: GridType) -> dict:
    pool, _ = fixture_pool(gt, [])
    rng = np.random.default_rng(23)
    pool += structured_grids(gt, rng)
    apply_cases, describe_cases, space_counts = {}, {}, {}
    for m in M.available(gt):
        cases = []
        for _ in range(APPLY_CASES):
            i = int(rng.integers(len(pool)))
            p = m.sample(rng, gt)
            y = m.apply(pool[i], p, gt)
            cases.append([i, jsonable(p), None if y is None else encode(y, gt)])
        apply_cases[m.id] = cases
        describe_cases[m.id] = [[jsonable(p), m.describe(p, gt), round(m.cost(p, gt), 9)]
                                for p in (m.sample(rng, gt) for _ in range(DESCRIBE_CASES))]
        space_counts[m.id] = sum(1 for _ in m.space(gt))
    avail = M.available(gt)
    sequences = []
    for _ in range(SEQUENCES):
        i = int(rng.integers(len(pool)))
        calls, g = [], pool[i]
        for _ in range(int(rng.integers(1, 5))):
            m = avail[int(rng.integers(len(avail)))]
            p = m.sample(rng, gt)
            calls.append({"m": m.id, "p": jsonable(p)})
            y = m.apply(g, p, gt)
            if y is not None:
                g = y
        sequences.append([i, calls, None if g == pool[i] else encode(g, gt)])
    return {"format": FORMAT + "-fixture", "version": DATA_VERSION,
            "gridType": {"size": gt.size, "symbols": gt.symbols, "colours": gt.colours, "key": gt.key},
            "pool": [encode(g, gt) for g in pool], "apply": apply_cases, "describe": describe_cases,
            "spaceCounts": space_counts, "sequences": sequences}


def write_index(entries: list[dict]) -> None:
    path = DATA_DIR / "mutators_index.ts"
    old = {}
    if path.exists():
        marker = "export const GRID_MUTATOR_INDEX = "
        txt = path.read_text()
        start = txt.index(marker) + len(marker)
        old = {e["key"]: e for e in json.loads(txt[start:].split(";\n", 1)[0])["gridTypes"]}
    old.update({e["key"]: e for e in entries})
    ents = sorted(old.values(), key=lambda e: (e["size"], e["symbols"], e["colours"]))
    meta = {"format": FORMAT + "-index", "version": DATA_VERSION, "gridTypes": ents}
    lines = [HEADER]
    lines += [f'import m{i} from "./{e["module"]}.ts";\n' for i, e in enumerate(ents)]
    lines += [f"export const GRID_MUTATOR_INDEX = {json.dumps(meta)};\n",
              "/** Raw JSON text of each GridType's mutator table, keyed by GridType key. Parse lazily. */\n",
              "export const GRID_MUTATOR_TEXT: Record<string, string> = {\n"]
    lines += [f'  "{e["key"]}": m{i},\n' for i, e in enumerate(ents)]
    lines.append("};\n")
    path.write_text("".join(lines))


def main(argv=None):
    ap = argparse.ArgumentParser(prog="gridlab.export_mutators")
    ap.add_argument("--types", nargs="*", default=list(DEFAULT_TYPES))
    a = ap.parse_args(argv)
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    FIXTURE_DIR.mkdir(parents=True, exist_ok=True)
    entries = []
    for spec in a.types:
        n, s, c = spec.split(",")
        gt = GridType(int(n), s, c)
        data = build_data(gt)
        mod = DATA_DIR / f"mutators_{slug(gt)}.ts"
        write_module(mod, data)
        fx = FIXTURE_DIR / f"mutators_{slug(gt)}.json"
        fx.write_text(json.dumps(build_fixture(gt), ensure_ascii=False, separators=(",", ":")) + "\n")
        total = sum(x["count"] for x in data["mutators"])
        entries.append({"key": gt.key, "module": f"mutators_{slug(gt)}", "size": gt.size, "symbols": gt.symbols,
                        "colours": gt.colours, "mutators": len(data["mutators"]), "params": total})
        print(f"{gt.key}: {len(data['mutators'])} mutators, {total} param settings, "
              f"{len(data['costPool'])} distinct costs; {mod.name} {mod.stat().st_size / 1024:.0f} KiB, "
              f"{fx.name} {fx.stat().st_size / 1024:.0f} KiB", flush=True)
    write_index(entries)


if __name__ == "__main__":
    main()
