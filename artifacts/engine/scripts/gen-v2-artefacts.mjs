#!/usr/bin/env node
/**
 * Bundles the committed valuation artefacts (lib/v2-valuation/artefacts/<variant>/<family>/*.json, spec §7.6) into
 * convex/v2/artefacts.gen.ts: what the server needs at run time (status, rungs, curve, content hash), without the
 * diagnostics. The server deals only rules whose artefact is here and dealable (capped: call (g)); values are looked up
 * from them.
 *
 *   node scripts/gen-v2-artefacts.mjs           write the file
 *   node scripts/gen-v2-artefacts.mjs --check   exit 1 if it is stale (test/unit/v2-artefacts.test.ts runs this)
 */
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(root, "..", "..", "lib", "v2-valuation", "artefacts");
const OUT = join(root, "convex", "v2", "artefacts.gen.ts");

export function generate() {
  const rows = [];
  for (const variant of readdirSync(SRC).sort())
    for (const family of readdirSync(join(SRC, variant)).sort())
      for (const file of readdirSync(join(SRC, variant, family)).filter(f => f.endsWith(".json")).sort()) {
        const a = JSON.parse(readFileSync(join(SRC, variant, family, file), "utf8"));
        rows.push({
          ruleKey: a.ruleKey, variant: a.variant, family: a.family, params: a.params, tieBreaker: a.tieBreaker, status: a.status,
          cap: a.cap, dealable: a.dealable, primarySense: a.primarySense, curve: a.curve, contentHash: a.contentHash,
          rungs: a.rungs.map(r => ({ score: r.score, label: r.label, layer: r.layer, ...(r.main !== undefined ? { main: r.main } : {}), bits: r.bits })),
        });
      }
  return `/** Generated by scripts/gen-v2-artefacts.mjs from lib/v2-valuation/artefacts: do not edit. */
import type { ArtefactRecord } from "./artefacts.ts";

export const ARTEFACT_RECORDS: readonly ArtefactRecord[] = ${JSON.stringify(rows, null, 1)};
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = generate();
  if (process.argv.includes("--check")) {
    if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== text) { console.error("convex/v2/artefacts.gen.ts is stale: run node scripts/gen-v2-artefacts.mjs"); process.exit(1); }
  } else writeFileSync(OUT, text);
}
