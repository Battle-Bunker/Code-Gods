/**
 * The human's side of an MCP OAuth connection (the engine UI's /connect page, browser scope only):
 *
 *   query    agent/connect:pending ({request})                                → what to review, and the human's rooms
 *   mutation agent/connect:approve ({request, roomId, permission, completion, ownerConsent?})
 *   mutation agent/connect:deny    ({request})
 *
 * Like device approval: the human must be a member of the chosen room; the permission may be lowered from
 * the requested scope, never raised; an owner grant needs the room's CURRENT owner and explicit consent
 * (ownership is checked again when the code is redeemed and on every call). After deciding, the page
 * sends the browser to GET /oauth/authorize/complete, which returns it to the client.
 *
 * The request key alone is not enough to collect the code: anyone who started the authorization knows it, and
 * could send it to a victim and poll /complete. So the approving page generates a one-time completion secret,
 * approve stores its hash, and /complete releases the code only to whoever presents that secret: the browser
 * that approved.
 */
import { ConvexError, v } from "convex/values";
import type { Doc } from "../_generated/dataModel";
import { mutation, query, type QueryCtx } from "../_generated/server";
import { requireViewer, type Permission, type Viewer } from "../auth/access";
import { sha256Hex } from "../auth/crypto";
import { memberOf } from "../lib/rooms";

const RANK: Record<Permission, number> = { read: 0, act: 1, owner: 2 };
const permission = v.union(v.literal("read"), v.literal("act"), v.literal("owner"));
const fail = (code: string, message: string): never => { throw new ConvexError({ code, message }); };
/** The completion secret's format (the page sends 32 random bytes, base64url). */
const COMPLETION = /^[A-Za-z0-9_-]{43,128}$/;

async function requireBrowser(ctx: QueryCtx): Promise<Viewer> {
  const viewer = await requireViewer(ctx);
  if (viewer.scope !== "browser") fail("FORBIDDEN", "Approval must come from a signed-in browser");
  return viewer;
}
async function requestFor(ctx: QueryCtx, key: string): Promise<Doc<"oauthRequests"> | null> {
  if (typeof key !== "string" || key.length < 20 || key.length > 128) return null;
  const keyHash = await sha256Hex(key);
  return ctx.db.query("oauthRequests").withIndex("by_key", q => q.eq("keyHash", keyHash)).unique();
}

const hostOf = (uri: string) => { try { return new URL(uri).hostname; } catch { return "(invalid)"; } };

export const pending = query({
  args: { request: v.string() },
  handler: async (ctx, { request: key }) => {
    const viewer = await requireBrowser(ctx);
    const request = await requestFor(ctx, key);
    if (!request || (request.subject && request.subject !== viewer.subject)) return null;
    const status = request.status === "pending" && request.expiresAt <= Date.now() ? "expired" as const : request.status;
    const memberships = await ctx.db.query("members").withIndex("by_god", q => q.eq("godId", viewer.subject)).take(200);
    const rooms = (await Promise.all(memberships.map(async m => {
      const room = await ctx.db.get(m.roomId);
      return room ? { roomId: room._id as string, shortCode: room.shortCode, isOwner: room.ownerId === viewer.subject, createdAt: room.createdAt } : null;
    }))).filter(r => r !== null).sort((a, b) => b.createdAt - a.createdAt);
    return {
      /** Self-reported by the client: NOT a verified identity. */
      clientName: request.clientName,
      clientId: request.clientId,
      /** Where the browser returns with the authorization code. */
      redirectUri: request.redirectUri, redirectHost: hostOf(request.redirectUri),
      permission: request.permission, resource: request.resource, status, expiresAt: request.expiresAt, rooms,
    };
  },
});

export const approve = mutation({
  args: { request: v.string(), roomId: v.string(), permission, completion: v.string(), ownerConsent: v.optional(v.boolean()) },
  handler: async (ctx, args) => {
    const viewer = await requireBrowser(ctx);
    if (!COMPLETION.test(args.completion)) fail("BAD_REQUEST", "completion must be 43-128 random base64url characters generated by this browser");
    const request = await requestFor(ctx, args.request);
    if (!request || request.status !== "pending" || request.expiresAt <= Date.now()) return fail("INVALID", "Invalid or expired connection request");
    if (RANK[args.permission] > RANK[request.permission]) fail("FORBIDDEN", `The client asked for ${request.permission}: you may lower the permission, not raise it`);
    const roomId = ctx.db.normalizeId("rooms", args.roomId);
    const room = roomId ? await ctx.db.get(roomId) : null;
    if (!room || !(await memberOf(ctx, room._id, viewer.subject))) return fail("FORBIDDEN", "Join this room first");
    if (args.permission === "owner") {
      if (room.ownerId !== viewer.subject) fail("FORBIDDEN", "Only the room's current owner can approve an owner grant");
      if (args.ownerConsent !== true) {
        fail("OWNER_CONSENT_REQUIRED", "An owner grant needs explicit consent: it can configure the room, spend its AI budget, start and end games and play as you");
      }
    }
    await ctx.db.patch(request._id, {
      status: "approved", subject: viewer.subject, roomId: room._id, grantedPermission: args.permission, completionHash: await sha256Hex(args.completion),
    });
    return { status: "approved" as const };
  },
});

export const deny = mutation({
  args: { request: v.string() },
  handler: async (ctx, args) => {
    const viewer = await requireBrowser(ctx);
    const request = await requestFor(ctx, args.request);
    if (!request || request.status !== "pending" || request.expiresAt <= Date.now()) return fail("INVALID", "Invalid or expired connection request");
    await ctx.db.patch(request._id, { status: "denied", subject: viewer.subject });
    return { status: "denied" as const };
  },
});
