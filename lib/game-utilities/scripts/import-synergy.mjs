// Import family synergy matrices exported by lib/grid-lab (python3 -m gridlab.explore.synergy.export
// --type n,sym,col writes lib/grid-lab/docs/explore/synergy_matrices/Grid_<n>_<sym>_<col>.<prior>.json) into
// data/synergy/, validate them, and regenerate data/synergy/index.js. Usage:
//   node lib/game-utilities/scripts/import-synergy.mjs [matrix.json ...]   (no args: re-index data/synergy/)
import { readFileSync, writeFileSync, readdirSync, copyFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = join(dirname(fileURLToPath(import.meta.url)), "..", "data", "synergy");
for (const file of process.argv.slice(2)) copyFileSync(file, join(dir, basename(file)));

const files = readdirSync(dir).filter(f => f.endsWith(".json")).sort();
for (const f of files) {
  const m = JSON.parse(readFileSync(join(dir, f), "utf8"));
  const n = m.families?.length;
  if (typeof m.instKey !== "string" || typeof m.priorId !== "string" || !n || m.w?.length !== n) throw new Error(`${f}: bad shape`);
  m.w.forEach((row, i) => {
    if (row.length !== n || row[i] !== 0) throw new Error(`${f}: row ${i} is not square with a zero diagonal`);
    row.forEach((x, j) => { if (!Number.isFinite(x) || x !== m.w[j][i]) throw new Error(`${f}: w is not finite and symmetric at ${i},${j}`); });
  });
}
writeFileSync(join(dir, "index.js"), [
  "// Generated by scripts/import-synergy.mjs: static imports of the shipped synergy matrices. Do not edit.",
  ...files.map((f, i) => `import m${i} from "./${f}" with { type: "json" };`),
  `export const MATRICES = [${files.map((_, i) => `m${i}`).join(", ")}];`, "",
].join("\n"));
writeFileSync(join(dir, "index.d.ts"), "// Generated by scripts/import-synergy.mjs. Do not edit.\nexport declare const MATRICES: readonly unknown[];\n");
console.log(`indexed ${files.length} synergy matrices`);
